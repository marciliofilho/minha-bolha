function interpolate(template: string, params?: Params): string {
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name])
  );
}

export function normalizeAppLanguage(value: unknown): AppLanguage {
  return value === 'en' || value === 'es' || value === 'pt' ? value : 'pt';
}

interface I18nContextValue {
  language: AppLanguage;
  t: (text: string, params?: Params) => string;
}

const I18nContext = createContext<I18nContextValue>({
  language: 'pt',
  t: (text, params) => interpolate(text, params)
});

export function I18nProvider({ children }: { children: ReactNode }) {
  const settings = useSettings();
  const language = normalizeAppLanguage(settings.data?.language);

  // Formatadores (datas, moeda) usam o idioma atual sem precisar alterar
  // todas as chamadas espalhadas pelo app.
  setAppLanguage(language);

  useEffect(() => {
    document.documentElement.lang = language;

    // Nome, aba e ícone acompanham o idioma do app.
    const brand = appBrand(language);
    document.title = brand.name;
    document
      .querySelector('meta[name="description"]')
      ?.setAttribute('content', `${brand.name} — ${brand.description}`);
    const icon = document.getElementById('app-icon');
    if (icon instanceof HTMLLinkElement) icon.href = brand.logo;
  }, [language]);

  const value = useMemo<I18nContextValue>(
    () => ({
      language,
      t: (text, params) => {
        const dictionary = language === 'en' ? EN : language === 'es' ? ES : null;
        return interpolate(brandText(dictionary?.[text] ?? text, language), params);
      }
    }),
    [language]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
